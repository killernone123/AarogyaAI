/**
 * AAROGYA-AI GEMINI AI INTEGRATION SERVICE
 *
 * SECURITY DESIGN:
 * ─────────────────────────────────────────────────────────────────────────────
 * • GEMINI_API_KEY is read from server-side .env only. Never exposed to client.
 * • All prompts are built server-side from structured application data.
 * • Gemini is asked to explain and interpret facts; it is NOT asked to invent
 *   inventory values, patient counts, or operational data.
 * • All Gemini outputs are parsed and validated against a schema before being
 *   returned to the client. Hallucinated numeric values are blocked.
 * • Fallback explanations (built from deterministic rules) are used whenever
 *   Gemini is unavailable, returns errors, or times out.
 * • Rate limiting is enforced per endpoint (see server.js).
 * ─────────────────────────────────────────────────────────────────────────────
 */

const GEMINI_API_BASE = 'https://generativelanguage.googleapis.com/v1beta/models';
const GEMINI_MODEL    = 'gemini-2.5-flash'; // lightweight, fast, sufficient for explanation tasks
const TIMEOUT_MS      = 15000; // 15-second hard timeout

/**
 * Core Gemini REST call with structured JSON request and timeout.
 *
 * @param {string} systemInstruction
 * @param {string} userPrompt
 * @param {string} apiKey
 * @returns {Promise<string>} text response
 */
async function callGemini(systemInstruction, userPrompt, apiKey) {
  const controller = new AbortController();
  const timeoutId  = setTimeout(() => controller.abort(), TIMEOUT_MS);

  const url = `${GEMINI_API_BASE}/${GEMINI_MODEL}:generateContent?key=${apiKey}`;

  const body = {
    system_instruction: {
      parts: [{ text: systemInstruction }]
    },
    contents: [
      {
        role: 'user',
        parts: [{ text: userPrompt }]
      }
    ],
    generationConfig: {
      temperature: 0.2,        // Low temperature = deterministic factual explanations
      maxOutputTokens: 800,
      topP: 0.8
    }
  };

  try {
    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
      signal: controller.signal
    });
    clearTimeout(timeoutId);

    if (!response.ok) {
      const errText = await response.text().catch(() => 'Unknown API error');
      throw new Error(`Gemini API returned status ${response.status}: ${errText.slice(0, 200)}`);
    }

    const json = await response.json();
    const text = json?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!text) throw new Error('Gemini returned an empty response.');
    return text;
  } catch (err) {
    clearTimeout(timeoutId);
    if (err.name === 'AbortError') throw new Error('Gemini API request timed out (15 s).');
    throw err;
  }
}

/**
 * System instruction used for all AarogyaAI calls.
 * Constrains Gemini to act as a supply-chain analyst only.
 */
const SYSTEM_INSTRUCTION = `
You are AarogyaAI Supply Intelligence, an AI assistant for district health supply-chain administrators in India's National Health Mission. Your role is to EXPLAIN and INTERPRET pre-computed data about medicine inventory, patient demand forecasts, and redistribution recommendations.

STRICT RULES:
1. NEVER invent, guess, or alter numeric values (stock quantities, patient counts, distances, consumption rates). Only use the numbers provided in the user prompt.
2. NEVER make clinical decisions (drug dosing, treatment protocols, diagnosis).
3. Always acknowledge that data is SYNTHETIC and for demonstration purposes only.
4. Provide explanations in clear, non-technical language suitable for a district health administrator.
5. When uncertainty exists, state it explicitly.
6. Keep responses concise: 3–5 short paragraphs maximum.
7. Do not include raw JSON or code in your response.
`.trim();

/**
 * Generate a Gemini narrative explanation for a demand forecast result.
 *
 * @param {Object} forecastResult   – output from forecastMedicineDemand / forecastFootfall
 * @param {string} apiKey
 * @returns {Promise<{explanation: string, source: 'gemini'|'fallback', error?: string}>}
 */
export async function getGeminiForecastExplanation(forecastResult, apiKey) {
  if (!apiKey) {
    return { explanation: buildFallbackForecastExplanation(forecastResult), source: 'fallback', error: 'GEMINI_API_KEY not configured.' };
  }

  // Build a fact-only prompt — Gemini cannot hallucinate values it has not been given
  const prompt = `
SYNTHETIC DEMONSTRATION DATA — HEALTHCARE SUPPLY FORECAST

The following forecast was generated by AarogyaAI's deterministic WMA algorithm for ${forecastResult.medicineName ?? 'district patient footfall'}. Please explain what this means for a district health administrator in simple terms.

DATA FACTS (do not alter any number):
- Centre: ${forecastResult.centerName ?? 'District-wide'}
- Forecast horizon: ${forecastResult.horizonDays} days
- Seasonal multiplier applied: ${forecastResult.seasonalFactor}x (${forecastResult.assumptions?.seasonalMultiplier ?? 'October monsoon-recession factor'})
- Current usable stock: ${forecastResult.currentUsableStock ?? 'N/A'} ${forecastResult.medicineName ? (forecastResult.unit ?? 'units') : 'patients'}
- Projected daily demand: ${forecastResult.projectedDailyDemand ?? forecastResult.projectedDailyBreakdown?.total ?? 'N/A'}
- Projected total demand over horizon: ${forecastResult.projectedTotalDemand ?? forecastResult.projectedTotalForHorizon ?? 'N/A'}
- Confidence interval: ±${forecastResult.confidenceInterval?.widthPercent ?? '?'}%
- Risk level: ${forecastResult.riskLevel ?? 'N/A'}
- Risk reason: ${forecastResult.riskReason ?? 'N/A'}
- Recommended replenishment: ${forecastResult.replenishmentRecommended ?? 'N/A'}

Important: Remind the administrator this is SYNTHETIC data for a hackathon demonstration, not real patient data.
`.trim();

  try {
    const text = await callGemini(SYSTEM_INSTRUCTION, prompt, apiKey);
    return { explanation: text.trim(), source: 'gemini' };
  } catch (err) {
    console.error('[GeminiService] Forecast explanation failed:', err.message);
    return {
      explanation: buildFallbackForecastExplanation(forecastResult),
      source: 'fallback',
      error: err.message
    };
  }
}

/**
 * Generate a Gemini narrative explanation for redistribution recommendations.
 *
 * @param {Object[]} recommendations  – array from redistributionEngine
 * @param {string}   apiKey
 * @returns {Promise<{explanation: string, source: 'gemini'|'fallback', error?: string}>}
 */
export async function getGeminiRedistributionExplanation(recommendations, apiKey) {
  if (!apiKey) {
    return { explanation: buildFallbackRedistributionExplanation(recommendations), source: 'fallback', error: 'GEMINI_API_KEY not configured.' };
  }

  if (!recommendations || recommendations.length === 0) {
    return { explanation: 'No redistribution recommendations were generated at this time. All facilities are within acceptable supply thresholds.', source: 'deterministic' };
  }

  // Send only top 3 recommendations to keep prompt small
  const top3 = recommendations.slice(0, 3);
  const factsBlock = top3.map((r, i) => `
Recommendation ${i + 1}:
- Drug: ${r.medicineName}
- Donor: ${r.donorCenterName} (current usable stock: ${r.donorUsableStockBefore} ${r.unit}, will retain ${r.donorUsableStockAfter} after transfer, above its threshold of ${r.donorMinThreshold})
- Recipient: ${r.recipientCenterName} (current: ${r.recipientUsableStockBefore} ${r.unit}, projected after: ${r.recipientUsableStockAfter})
- Transfer quantity: ${r.transferQuantity} ${r.unit}
- Distance: ${r.distanceKm !== null ? r.distanceKm + ' km' : 'distance unknown'}
- Reason: ${r.riskReason}
`.trim()).join('\n\n');

  const prompt = `
SYNTHETIC DEMONSTRATION DATA — DISTRICT SUPPLY REDISTRIBUTION RECOMMENDATIONS

AarogyaAI has identified the following redistribution opportunities. Explain each recommendation to a district health administrator in simple language. Emphasise why acting quickly matters for patient safety, without being alarmist.

${factsBlock}

IMPORTANT: These recommendations require ADMINISTRATOR APPROVAL before any physical transfer occurs. No automatic transfer has been triggered. Remind the administrator this is SYNTHETIC simulation data.
`.trim();

  try {
    const text = await callGemini(SYSTEM_INSTRUCTION, prompt, apiKey);
    return { explanation: text.trim(), source: 'gemini' };
  } catch (err) {
    console.error('[GeminiService] Redistribution explanation failed:', err.message);
    return {
      explanation: buildFallbackRedistributionExplanation(recommendations),
      source: 'fallback',
      error: err.message
    };
  }
}

// ── Deterministic fallback explanations ─────────────────────────────────────

function buildFallbackForecastExplanation(result) {
  if (!result.success) {
    return `Forecast unavailable: ${result.error || 'Insufficient historical data for projection.'}`;
  }
  const days = result.projectedDaysUntilStockout ?? result.horizonDays;
  const risk = result.riskLevel ?? 'UNKNOWN';
  return [
    `Based on a ${result.horizonDays}-day synthetic demand forecast using the Weighted Moving Average algorithm, the projected daily demand for ${result.medicineName ?? 'this drug'} at ${result.centerName ?? 'this facility'} is ${result.projectedDailyDemand ?? 'N/A'} ${result.unit ?? 'units'}/day (±${result.confidenceInterval?.widthPercent ?? '?'}% confidence).`,
    `A seasonal multiplier of ${result.seasonalFactor}x has been applied to account for the October/November vector-borne disease surge pattern typical in Karnataka districts.`,
    `Risk assessment: ${risk}. ${result.riskReason ?? ''}`,
    `NOTE: All data is synthetically generated for demonstration. This forecast does not reflect real patient demand or actual inventory.`
  ].join(' ');
}

function buildFallbackRedistributionExplanation(recommendations) {
  if (!recommendations || recommendations.length === 0) {
    return 'No redistribution recommendations generated. All facilities appear to be within acceptable supply thresholds based on the current synthetic data.';
  }
  const lines = recommendations.slice(0, 3).map(r =>
    `• Transfer ${r.transferQuantity} ${r.unit} of ${r.medicineName} from ${r.donorCenterName} to ${r.recipientCenterName} (${r.distanceKm !== null ? r.distanceKm + ' km' : 'distance N/A'}). Reason: ${r.riskReason.slice(0, 160)}...`
  );
  return [
    'AarogyaAI has identified the following supply imbalances across district health facilities:',
    ...lines,
    'Each transfer requires explicit administrator approval and physical logistics coordination. No automatic stock movement has occurred. All data is SYNTHETIC.'
  ].join('\n');
}
